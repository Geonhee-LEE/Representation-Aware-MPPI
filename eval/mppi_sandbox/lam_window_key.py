#: Every cell anybody has re-measured off key. This registry is the difference
#: between an anecdote and a rate: with one cell, "windows move off support" is
#: a story about `cafe_obstacle_crossing_v0`, which has disjoint per-arm windows
#: and a 5-actor dynamic block and is the pathological scene by construction.
#: :func:`shift_census` reads it, and reads *all* of it — a census that quoted
#: only the cells that moved would be the selection D-107 books.
#: With three cells the split is **4 of 6 arm-cells held**, and — this is what
#: the third cell bought — the two that did not are attributable. Two cells
#: differing in both scene and weight supported no attribution at all; adding
#: head_on at `w = 150` gives a scene contrast at fixed weight and a weight
#: contrast at fixed scene, and :func:`attribution` grades them `FACTOR_MOVES`
#: and `FACTOR_INERT` respectively. **The mover is the scene, not the weight.**
#:
#: Note the design property rather than the number: the registry is informative
#: in proportion to how much its cells *share*, not to how many there are. A
#: fourth cell at a fresh (scene, weight) pair would add two arm-cells to the
#: census and zero contrasts to the attribution.
REMEASURED: tuple[Remeasurement, ...] = (
    CROSSING_W150_CELL, HEADON_W100_CELL, HEADON_W150_CELL,
)


def remeasurement(scenario: str, weight: float) -> Remeasurement | None:
    """The re-measured cell for this `(scene, weight)`, or `None`.

    `None` is the common answer and is not a failure: the registry holds the
    handful of cells somebody paid ~450 s to walk, not the table's ~16.
    """
    scenario = os.path.basename(scenario)
    for cell in REMEASURED:
        if cell.scenario == scenario and cell.weight == float(weight):
            return cell
    return None


def shift_census(path: str = TABLE) -> dict[str, tuple[str, ...]]:
    """Every re-measured **arm-cell**, grouped by its :func:`window_shift`.

    The unit is the arm-cell and not the cell, because the two arms of one
    scene can grade differently — D-134's crossing is `WINDOW_DISJOINT` on risk
    and `WINDOW_CLOSED` on stock, and collapsing those to one verdict per scene
    would lose exactly the asymmetry that made the rung unscorable.

    Returned as grade → sorted arm-cell labels rather than as a bare count, so
    a caller reporting "k of n held" can also name which k. A rate whose
    numerator cannot be enumerated is the shape `published_ratios` refuses.
    """
    out: dict[str, list[str]] = {}
    for cell in REMEASURED:
        for arm in cell.arms:
            label = f"{cell.scenario}:{arm}@w={cell.weight:g}"
            out.setdefault(cell.shift(arm, path), []).append(label)
    return {grade: tuple(sorted(labels)) for grade, labels in out.items()}


# --- what the census can attribute, and to which axis ------------------------

#: The two axes a re-measured cell is keyed by. A grade difference between two
#: cells is attributable to one of them only if the **other** is held fixed.
SCENE = "scene"
WEIGHT = "weight"


def _level(cell: Remeasurement, factor: str):
    return cell.scenario if factor == SCENE else cell.weight


def _other(factor: str) -> str:
    if factor not in (SCENE, WEIGHT):
        raise ValueError(f"unknown factor {factor!r}")
    return WEIGHT if factor == SCENE else SCENE


def contrasts(factor: str,
              cells: Sequence[Remeasurement] = REMEASURED,
              ) -> tuple[tuple[Remeasurement, Remeasurement], ...]:
    """Cell pairs that **isolate** `factor`: they differ in it and agree on the
    other axis.

    This reads the registry's experimental design off the registry, rather than
    asserting it in prose. The module preamble's "the census cannot yet separate
    those two axes" was true when written, and a sentence like that is exactly
    the kind that outlives the measurement falsifying it — D-047's shape. With
    the two cells the registry opened with, this returns `()` for both factors:
    crossing was walked at `w = 150` and head_on at `w = 100`, so the one pair
    available differs in *both* axes and isolates neither.
    """
    other = _other(factor)
    out = []
    for i, a in enumerate(cells):
        for b in cells[i + 1:]:
            if (_level(a, other) == _level(b, other)
                    and _level(a, factor) != _level(b, factor)):
                out.append((a, b))
    return tuple(out)


#: No pair of cells isolates the factor, so no outcome can be attributed to it.
#: Not a statement that the factor is inert — a statement that the registry
#: cannot tell. This is the state the two-cell registry was in on both axes.
NO_CONTRAST = "NO_CONTRAST"

#: The factor is isolated and the arms on either side of the contrast grade
#: **differently**: moving this axis alone moves the window.
FACTOR_MOVES = "FACTOR_MOVES"

#: The factor is isolated and every comparable arm grades the **same** across
#: it. Moving this axis alone does not move the window, so a difference seen
#: elsewhere in the census belongs to the other axis.
FACTOR_INERT = "FACTOR_INERT"


def attribution(factor: str, path: str = TABLE,
                cells: Sequence[Remeasurement] = REMEASURED) -> str:
    """Can the registry attribute a window shift to `factor`, and does it move?

    Compared **per arm** across each isolating pair, because `shift_census`'s
    unit is the arm-cell for the reason recorded there: one scene's two arms
    can grade differently, and a cell-level comparison would average away the
    asymmetry that is usually the finding.

    `NO_CONTRAST` is returned both when no pair isolates the factor and when
    the isolating pairs share no arm — in both cases the honest answer is that
    nothing was compared, and collapsing "cannot tell" into `FACTOR_INERT`
    would be the empty-denominator failure D-107/D-120/D-127 each booked.
    """
    compared = False
    for a, b in contrasts(factor, cells):
        for arm in sorted(set(a.arms) & set(b.arms)):
            compared = True
            if a.shift(arm, path) != b.shift(arm, path):
                return FACTOR_MOVES
    return FACTOR_INERT if compared else NO_CONTRAST


# --- comparing two whole tables, rather than two hand-walked cells -----------

#: The cell had **no** window in the reference table either, so its
#: :data:`WINDOW_CLOSED` at the new weight is not a closure — there was nothing
#: to close. Graded apart because `window_shift` cannot tell the two apart: it
#: reports `WINDOW_CLOSED` whenever the new window is empty, whether or not the
#: recorded one was. Folding these in would inflate the "moved" count with cells
#: that never had an operating point at any weight (Q-035), which is the
#: empty-denominator shape D-107/D-120/D-127 each booked.
NEVER_OPEN = "NEVER_OPEN"


def table_shift_census(reference: str, remeasured: str,
                       arms: Sequence[str] | None = None,
                       ) -> dict[str, tuple[str, ...]]:
    """Grade **every** arm-cell of two calibration tables against each other.

    :func:`shift_census` reads the :data:`REMEASURED` registry — the handful of
    cells somebody paid ~450 s each to walk by hand. This reads two generated
    tables instead, which is a different and much wider source: `calibrate_lam`
    at two weights produces the same 16 arm-cells twice, so every cell is its
    own weight contrast with the scene held fixed **by construction**. The
    registry needed :func:`contrasts` to find pairs that isolate an axis; here
    the isolation is structural and there is nothing to search for.

    The grade is :func:`window_shift`, not a second scale of its own — the two
    sources must stay comparable, and a table-specific grading rule would be the
    D-047 shape where the copy is the one that drifts.

    Both tables must be keyed and keyed *differently*; comparing a table to
    itself would report `WINDOW_HELD` everywhere and mean nothing.

    `arms` restricts the census to those controller columns. It exists because
    a column can be bought at one weight and not another — D-146 calibrated
    `gap_gated_mppi` at `w = 10` only — and the two honest readings of that are
    "refuse, the tables are not comparable" and "compare the columns both
    tables have, and say which you dropped". Silently intersecting is the third
    and it is the one this refuses: a census whose denominator quietly shrinks
    reports a *rate* over a population nobody stated. The excluded columns are
    the caller's to name; what is enforced here is that `arms` cannot invent
    one, so a typo shrinks nothing.
    """
    ref_rows, ref_w = _rows(reference)
    new_rows, new_w = _rows(remeasured)
    if ref_w is None or new_w is None:
        raise ValueError(
            f"both tables must be keyed: {reference} -> {ref_w}, "
            f"{remeasured} -> {new_w}")
    if ref_w == new_w:
        raise ValueError(
            f"both tables are keyed at w={ref_w:g}; a table compared to its own "
            "weight grades WINDOW_HELD everywhere and witnesses nothing")

    def by_key(rows):
        return {(os.path.basename(c["scenario"]), c["controller"]): c
                for c in rows}

    ref, new = by_key(ref_rows), by_key(new_rows)
    if arms is not None:
        wanted = set(arms)
        for table, cells in ((reference, ref), (remeasured, new)):
            missing = wanted - {arm for _scene, arm in cells}
            if missing:
                raise ValueError(
                    f"{table} has no column for {sorted(missing)}; `arms` "
                    f"selects columns to compare, it cannot create them")
        ref = {k: v for k, v in ref.items() if k[1] in wanted}
        new = {k: v for k, v in new.items() if k[1] in wanted}
    if set(ref) != set(new):
        raise ValueError(
            f"tables cover different cells: {sorted(set(ref) ^ set(new))}")

    out: dict[str, list[str]] = {}
    for key in sorted(ref):
        scene, arm = key
        recorded = tuple(float(x) for x in ref[key]["admissible"])
        measured = tuple(float(x) for x in new[key]["admissible"])
        grade = window_shift(recorded, measured)
        if grade == WINDOW_CLOSED and not recorded:
            grade = NEVER_OPEN
        out.setdefault(grade, []).append(f"{scene}:{arm}")
    return {grade: tuple(sorted(labels)) for grade, labels in out.items()}


# --- the seed-count axis, isolable only where the two sources overlap --------

@dataclass(frozen=True)
class SeedContrast:
    """What a generated table and a hand-walked cell say about the **same**
    `(scene, weight)`, and therefore about the seed count alone.

    Every table `calibrate_lam` writes carries an 8-seed caveat that has stood
    since D-142 and has never been priced, because pricing it needs the same
    cell measured twice at two seed counts — and until a table exists at a
    weight the :data:`REMEASURED` registry also holds, no such pair exists.
    `w = 100` is the first weight where it does: the table walks 8 seeds and
    :data:`HEADON_W100_CELL` walked 16, at the same scene, weight and margin.

    Two confounds are handled rather than assumed away:

      * **The ladders differ.** The generated tables walk 8 rungs and the hand
        walks walked 4, so a table window containing 0.05 would read as a
        disagreement about a rung the hand walk never tested. The grade is
        scoped to :attr:`ladder` — the registry cell's rungs — and the table
        rungs that fall outside it are named in :attr:`unwalked` rather than
        silently included or silently dropped.
      * **Non-comparison is visible.** Registry cells at other weights are
        listed in :attr:`uncompared` with their weights. A census that showed
        only the cell it could compare would read as "the caveat is priced"
        when what happened is that one of three cells could be looked at.

    And a third, which only became reachable when a table stopped covering the
    whole matrix (D-149). :attr:`absent` is the cell the table is at the right
    weight for and simply **does not contain** — a case that cannot arise while
    every table walks all 8 scenes, and arrives the moment one walks 1.
    `Remeasurement.recorded` resolves through :func:`lookup`, which returns an
    empty `admissible` for a missing cell exactly as it does for a measured-and-
    windowless one, and `window_shift` reads the empty side as `recorded <= new`
    — so an absent cell grades **WINDOW_HELD** and lands in :attr:`exact` when
    the hand walk is windowless too. That is not a weak reading, it is a
    fabricated one: the census would report that the cheap table reproduces an
    expensive walk on a scene the cheap table never visited, and it would count
    it in :attr:`compared`. Absent cells are therefore diverted **before**
    grading. This is Q-034's distinction (`NO_CELL` is not `EMPTY_WINDOW`) at
    the one layer that had lost it; `lookup` never lost it — it carries
    `found`, and `recorded` is where the bit was being dropped.
    """

    table: str
    weight: float
    ladder: tuple[float, ...]
    graded: Mapping[str, tuple[str, ...]]
    #: Arm-cells where the two windows are **equal**, not merely contained.
    #: `WINDOW_HELD` is `recorded <= remeasured`, so a table narrower than the
    #: hand walk grades HELD while disagreeing; D-135 made exactly this
    #: distinction about its own result and it is the one that matters here,
    #: since a cheap measurement agreeing by being conservative is a different
    #: claim from one agreeing outright.
    exact: tuple[str, ...]
    unwalked: tuple[float, ...]
    uncompared: tuple[str, ...]
    #: Arm-cells hand-walked at **this** weight that the table has no row for.
    #: Not graded and not counted in :attr:`compared` — see the third bullet
    #: above. Empty for any table that covers the registry's scenes.
    absent: tuple[str, ...] = ()

    @property
    def compared(self) -> int:
        return sum(len(v) for v in self.graded.values())

    @property
    def verdict(self) -> str:
        """:data:`SEED_CONTRASTED` or :data:`NO_SEED_CONTRAST` — whether this
        census priced the seed caveat *at all*.

        Every other field on this class reads identically under "the table
        agreed everywhere" and "the table was never checked": `graded` is
        empty, `exact` is empty, and — since D-149 — `absent` is empty too,
        because there was no registry cell here to be absent from. Three of
        the five shipped tables are in that state (`w = 10`, `w = 75`,
        `w = 250`), and a caller that reads `not census.exact` as "no
        disagreement" gets the wrong answer for all three.

        `NO_SEED_CONTRAST` has named this case since D-145 wrote it, and
        nothing returned it; :func:`attribution` had already made the same
        split one function over (`FACTOR_INERT if compared else NO_CONTRAST`)
        for the same reason. This is the empty denominator reading as a pass
        — D-107 / D-120 / D-127 — on the one axis where the constant existed
        but the branch did not.
        """
        return SEED_CONTRASTED if self.compared else NO_SEED_CONTRAST


#: No cell in the registry was hand-walked at the table's weight, so the seed
#: count cannot be isolated against it. Distinct from "the seed count does not
#: matter": nothing was compared. Same shape as :data:`NO_CONTRAST`.
NO_SEED_CONTRAST = "NO_SEED_CONTRAST"

#: At least one arm-cell was hand-walked at this table's weight and graded
#: against it, so :attr:`SeedContrast.graded` / :attr:`SeedContrast.exact` are
#: answers rather than silence. It does **not** say the two agreed — that is
#: what `exact` is for. Same shape as :data:`FACTOR_INERT` / :data:`NO_CONTRAST`:
#: the verdict says whether the question was asked, the fields say what it
#: answered.
SEED_CONTRASTED = "SEED_CONTRASTED"


def seed_census(path: str, cells: Sequence[Remeasurement] = REMEASURED,
                ) -> SeedContrast:
    """Grade a generated table against every hand-walked cell at **its** weight.

    Direction follows :meth:`Remeasurement.shift`: the table is `recorded` (the
    set a caller would actually have used) and the hand walk is `remeasured`
    (the more expensive measurement it is checked against). So `WINDOW_HELD`
    reads "everything the cheap table offers, the expensive walk confirms".

    Scoped to the registry cell's ladder for the reason in :class:`SeedContrast`
    — outside it the two sources are not disagreeing, they are answering
    different questions.
    """
    rows, table_w = _rows(path)
    if table_w is None:
        raise ValueError(
            f"{path} records no calibration_weight, so no registry cell can be "
            "matched to it; the seed axis needs the weight held fixed")
    comparable = [c for c in cells if c.weight == float(table_w)]
    uncompared = tuple(sorted(
        f"{c.scenario}@w={c.weight:g}" for c in cells if c not in comparable))
    ladder: tuple[float, ...] = ()
    unwalked: tuple[float, ...] = ()
    out: dict[str, list[str]] = {}
    exact: list[str] = []
    absent: list[str] = []
    for cell in comparable:
        ladder = tuple(sorted(set(ladder) | set(cell.ladder)))
        for row in rows:
            if os.path.basename(row["scenario"]) == cell.scenario:
                unwalked = tuple(sorted(
                    set(unwalked)
                    | {float(x) for x in row.get("ladder", ())} - set(cell.ladder)))
        for arm in cell.arms:
            rungs = set(cell.ladder)
            label = f"{cell.scenario}:{arm}@w={cell.weight:g}"
            if not lookup(path, cell.scenario, arm, cell.weight).found:
                absent.append(label)   # no row here — not an empty window
                continue
            table_window = tuple(
                x for x in cell.recorded(arm, path) if x in rungs)
            walked = tuple(x for x in cell.window(arm) if x in rungs)
            out.setdefault(window_shift(table_window, walked), []).append(label)
            if set(table_window) == set(walked):
                exact.append(label)
    return SeedContrast(
        table=path, weight=float(table_w), ladder=ladder,
        graded={g: tuple(sorted(v)) for g, v in out.items()},
        exact=tuple(sorted(exact)), unwalked=unwalked, uncompared=uncompared,
        absent=tuple(sorted(absent)))

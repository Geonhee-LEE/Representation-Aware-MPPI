"""At what barrier weight was `lam_windows.yaml` measured, and is that the
weight you are about to run at?

The table cannot answer the first half of that question. `lam_windows.yaml` is
keyed by `(scenario, controller)` and records `ladder`, `seeds`, `band_width`,
`min_spread` — every axis of the measurement except the one that turned out to
matter. It was generated by `calibrate_lam` with the controllers at their
shipped `MPPIParams().w_obs_soft = 10.0`, and since D-131 it has been read at
weights of 30, 75, 100, 150, 300, 500, 750, 1000, 2000. Nothing in the file
says 10, so nothing in a consumer could notice it was reading off-key.

Why an off-key read is not a small error
----------------------------------------

`comparison_headroom`'s preamble has said "λ calibration is not weight-
invariant" since D-131, and D-133 paid for it. On `cafe_obstacle_crossing_v0`
the table's `risk_mppi` window is `[1.6, 3.2]`, so the crossing ladder was
walked at λ = 3.2 as the risk arm's admissible temperature. **At `w = 150` that
is the wrong decade**: measured 2026-08-08, 16 seeds, `w_obs_soft = 150`, the
risk arm weights in band at λ = 0.8 (16/16) and at **neither** recorded rung —
1.6 is 0/16 — see :data:`CROSSING_W150_ESS`. The window did not widen or
narrow; it **moved off its recorded support entirely**. The baseline arm is
worse still: its recorded `[0.4, 0.8]` is empty at `w = 150` (12/16 and 8/16 in
band), so that cell has no admissible temperature on the walked ladder at all.

That is the difference between a guard worth having and paranoia. An off-key
lookup is not "a number measured under slightly different conditions"; on that
cell it is a temperature the arm is *not* admissible at, handed to a caller that
will then report a mechanism delta from a sampler running at ESS 2.

…and the difference between paranoia and a rate
------------------------------------------------

A guard justified by one cell is justified by the *worst* cell: crossing has
disjoint per-arm windows and a 5-actor dynamic block and is the pathological
scene by construction. Q-117 bought the second cell, and it grades the other
way. `cafe_head_on_v0` at `w = 100` — the operating point D-131/D-132's band was
measured at — re-measures to **exactly** its recorded `[0.2, 0.4, 0.8]` on both
arms, every rung 16/16 (:data:`HEADON_W100_CELL`). So `WINDOW_HELD` is a
witnessed outcome and not a branch nobody reaches, the project's one significant
mechanism claim was walked at admissible temperatures, and the honest headline
is **4 of 6 re-measured arm-cells held** (:func:`shift_census`) rather than
"windows move".

Which half a future cell lands in is no longer unpredicted. Q-118 walked
head_on a second time at `w = 150` — crossing's weight — and it held there too
(:data:`HEADON_W150_CELL`), which is the one walk that separates the two axes:
at fixed `w = 150` the scene contrast grades `FACTOR_MOVES`, and at fixed scene
the weight contrast grades `FACTOR_INERT` (:func:`attribution`). **Windows move
on the pathological scene, not at the higher weight.** So an off-key read is a
scene-shaped risk: it is crossing's disjoint per-arm windows that make the
table unreliable, and head_on tolerates a 15× weight excursion without moving a
rung.

That narrows the guard's justification rather than widening it, and it is worth
saying which way that cuts. `OFF_KEY` still refuses on both scenes, because a
lookup cannot know it is on the benign one until somebody has paid ~300 s to
find out — the refusal is cheap and the re-measurement is not.

What this module does, and the smaller half it deliberately is
--------------------------------------------------------------

Q-116's fork was (a) re-key the whole table by weight — a full re-calibration,
~500 runs per weight, times however many weights the project ends up caring
about — or (b) **guard first, re-key later**. This is (b), and (b) is chosen
because the guard is what makes (a) schedulable: until a lookup can *refuse*,
there is no list of the sites that need re-keying and no way to tell whether a
past result depended on one.

So: :func:`lookup` returns a `WindowLookup` that carries a verdict, and its
`usable` property is `None` on every refusal. It does **not**:

  * **Extrapolate.** No nearest-weight fallback, no interpolation between two
    measured weights. :data:`CROSSING_W150` is one cell at one weight; two
    points on one cell do not describe how windows move, and a fallback would
    be a model of that motion dressed as a lookup.
  * **Re-key the file.** The table stays as generated. Adding a
    `calibration_weight:` field is `calibrate_lam`'s write, and it should be
    written by a run that *measured* at that weight — hand-stamping the file
    with `10.0` would make every existing row claim a provenance nobody
    re-derived, which is the shape D-107 booked.

    *Since 2026-08-08 that write exists* (D-138): `calibrate_lam --w-obs-soft`
    walks the ladder at a chosen weight and `to_yaml` emits
    `calibration_weight:` read off the cells themselves. The shipped
    `lam_windows.yaml` is still **unkeyed and still grades `UNKEYED`**, and
    deliberately so — keying it means *re-running* the matrix, not editing the
    header, and that is ~500 closed-loop runs this module is not entitled to
    fake. What changed is that the refusal is now clearable: before, `ON_KEY`
    was unreachable by any means, and D-044 already booked what becomes of a
    check nobody can satisfy.
  * **Decide whether the caller's weight matters.** `UNKEYED` is not a
    softened `OFF_KEY`; it is the stronger statement, because a table with no
    weight field cannot even be checked. Both refuse, and they refuse under
    different names so the fix for each is legible: `OFF_KEY` needs a
    measurement at the caller's weight, `UNKEYED` needs the file to record what
    it already knows.

The on-key case is not vacuous
-------------------------------

A guard that refused every call would be `guard_vacuity`'s complaint with the
sign flipped — always-fires is as uninformative as never-fires. `ON_KEY` is
reachable and is the common case for the ~24 cells `baseline_matrix` resolves
at the shipped weight: those callers run at `w_obs_soft = 10` and the table was
measured there, so they keep the window they have always had. What changes is
that a *ladder walk* — the only kind of caller that varies the weight — now has
to say which weight its window came from.

Typical use::

    look = lookup(TABLE, "cafe_obstacle_crossing_v0.yaml", "risk_mppi", 150.0)
    if look.usable is None:
        raise AssertionError(str(look))   # verdict names the missing measurement
    for lam in look.usable:
        ...
"""

from __future__ import annotations

import os
from dataclasses import dataclass
from typing import Mapping, Sequence

try:
    import yaml as _yaml
except ImportError:                                      # pragma: no cover
    _yaml = None

#: The weight every row of the *shipped* `lam_windows.yaml` was measured at:
#: `MPPIParams().w_obs_soft`. Stated here as the *externally known* provenance
#: of a file that does not record it — which is why `UNKEYED` exists rather
#: than this constant being silently substituted for the missing field.
#:
#: This is a fact about one file, not about the generator. Since D-138
#: `calibrate_lam --w-obs-soft` can walk any weight and records it, so a table
#: produced today may legitimately carry any value; read it from
#: `calibration_weight:` (what :func:`_rows` does) and use this constant only
#: when speaking about the historical shipped table.
CALIBRATION_WEIGHT = 10.0

#: Default table location, matching `calibrate_lam --out`.
TABLE = "eval/scenarios/lam_windows.yaml"

#: The caller's weight equals the weight this row was measured at. The window
#: is usable as recorded.
ON_KEY = "ON_KEY"

#: The row records a calibration weight and it is **not** the caller's. The
#: window says nothing about this operating point; a measurement at the
#: caller's weight is the only thing that fixes it.
OFF_KEY = "OFF_KEY"

#: The table records no calibration weight at all, so no row in it can be
#: checked against any caller. This is the state `lam_windows.yaml` is in as
#: shipped, and it is the strongest refusal of the three.
UNKEYED = "UNKEYED"

#: No `(scenario, controller)` row. Distinct from an empty window: an absent
#: cell was never measured, an empty one was measured and found inadmissible
#: everywhere (`calibratable: false`).
NO_CELL = "NO_CELL"

#: The row exists, is on key, and its admissible list is empty — this (scene,
#: controller) is not an ablation surface at any tested temperature (Q-035).
#: Graded separately from `NO_CELL` because the caller's next move differs:
#: measure vs. give up on the cell.
EMPTY_WINDOW = "EMPTY_WINDOW"

#: Refusing verdicts — `usable` is `None` under each.
REFUSALS = frozenset({OFF_KEY, UNKEYED, NO_CELL, EMPTY_WINDOW})


@dataclass(frozen=True)
class WindowLookup:
    """One `(scenario, controller)` window, resolved against a caller's weight.

    `measured_at` is `None` when the table carries no weight key — the value is
    *unknown*, not assumed to be :data:`CALIBRATION_WEIGHT`. That distinction is
    the whole module: substituting the constant would make every current lookup
    read `ON_KEY` at `w = 10` and `OFF_KEY` elsewhere, which is the right answer
    for the wrong reason and would go silently wrong the day someone regenerates
    the table at another weight.
    """

    scenario: str
    controller: str
    #: The weight the caller intends to run at.
    weight: float
    #: The row's `admissible` list as recorded, `()` when the row is absent.
    admissible: tuple[float, ...]
    #: The weight the row was calibrated at; `None` when the table is unkeyed.
    measured_at: float | None
    #: Whether a row for this `(scenario, controller)` was found at all.
    found: bool = True

    @property
    def verdict(self) -> str:
        if not self.found:
            return NO_CELL
        if self.measured_at is None:
            return UNKEYED
        if self.measured_at != self.weight:
            return OFF_KEY
        return EMPTY_WINDOW if not self.admissible else ON_KEY

    @property
    def usable(self) -> tuple[float, ...] | None:
        """The window, or `None` under every refusal. Callers that want the
        recorded numbers regardless of provenance read `admissible` and say so
        at the call site."""
        return None if self.verdict in REFUSALS else self.admissible

    def __str__(self) -> str:
        at = "unrecorded" if self.measured_at is None else f"{self.measured_at:g}"
        return (
            f"{self.scenario} {self.controller} w={self.weight:g} :: "
            f"{self.verdict} [window={list(self.admissible)} "
            f"measured_at={at}]"
        )


def _rows(path: str) -> tuple[list[dict], float | None]:
    """`(cells, calibration_weight)` from a table file. The weight is read from
    a top-level `calibration_weight:` key and is `None` when absent — the file
    as generated has no such key, and inventing one here is the substitution
    the class docstring refuses."""
    if _yaml is None:                                    # pragma: no cover
        raise RuntimeError("pyyaml required to read the calibration table")
    raw = _yaml.safe_load(open(path)) or {}
    weight = raw.get("calibration_weight")
    return list(raw.get("cells") or []), (
        None if weight is None else float(weight)
    )


def lookup(path: str, scenario: str, controller: str,
           weight: float) -> WindowLookup:
    """Resolve one window against the weight the caller will run at.

    `scenario` matches the table's `scenario:` field, which holds a bare
    basename (`cafe_head_on_v0.yaml`); a path is accepted and reduced to its
    basename so call sites can pass whatever they already hold.

    The match is on the **stem**, so `cafe_head_on_v0`, `cafe_head_on_v0.yaml`
    and `eval/scenarios/cafe_head_on_v0.yaml` name one scene — because they do.
    The basename-only rule was written when every caller was a test holding a
    table-shaped key; `comparison_headroom.Headroom.scenario` records the
    extensionless form, so under the old rule the guard's first non-test
    consumer graded **every** row `NO_CELL` (D-144). A refusal caused by a
    filename suffix is indistinguishable, at the call site, from one caused by
    an uncalibrated cell — and it fails in the vacuous direction, where a guard
    that refuses everything looks maximally strict and checks nothing.
    Normalisation is applied symmetrically to both sides; the caller's own
    spelling is what gets stored back on :class:`WindowLookup`.
    """
    scenario = os.path.basename(scenario)
    key = os.path.splitext(scenario)[0]
    cells, measured_at = _rows(path)
    for cell in cells:
        if (os.path.splitext(os.path.basename(str(cell.get("scenario", ""))))[0] == key
                and cell.get("controller") == controller):
            return WindowLookup(
                scenario=scenario, controller=controller,
                weight=float(weight),
                admissible=tuple(float(x) for x in cell.get("admissible") or ()),
                measured_at=measured_at,
            )
    return WindowLookup(scenario=scenario, controller=controller,
                        weight=float(weight), admissible=(),
                        measured_at=measured_at, found=False)


#: The window **held**: the re-measured admissible set contains the recorded
#: one, so a caller using the recorded window would have run in band.
WINDOW_HELD = "WINDOW_HELD"

#: The window **moved but overlaps**: some recorded rung survives, some does
#: not. A caller picking `max(recorded)` and a caller picking `min(recorded)`
#: get different answers about their own admissibility, so this is graded apart
#: from `HELD` even though the sets intersect.
WINDOW_SHIFTED = "WINDOW_SHIFTED"

#: The window moved **off its recorded support**: no recorded rung is
#: admissible at the new weight. Every rung a caller could have taken from the
#: table is one the arm does not weight in band at.
WINDOW_DISJOINT = "WINDOW_DISJOINT"

#: The arm is admissible at **no** rung at the new weight. Not a movement — the
#: window closed, and the cell has no operating point at this weight at all.
WINDOW_CLOSED = "WINDOW_CLOSED"


def window_shift(recorded: Sequence[float],
                 remeasured: Sequence[float]) -> str:
    """Grade a re-measurement of one cell's window at a different weight.

    This is what makes the off-key refusal non-vacuous: without a witness that
    windows *move*, `OFF_KEY` is a rule nobody can show costs anything. It is
    deliberately a four-way grade and not a boolean, because "the window moved"
    covers both the case where a caller would have been fine (`SHIFTED`, if it
    happened to pick a surviving rung) and the case where no choice it could
    have made was admissible (`DISJOINT`). D-133's cell is `DISJOINT`.
    """
    rec, new = set(float(x) for x in recorded), set(float(x) for x in remeasured)
    if not new:
        return WINDOW_CLOSED
    if rec <= new:
        return WINDOW_HELD
    return WINDOW_SHIFTED if rec & new else WINDOW_DISJOINT


def admissible_at(counts: Mapping[float, tuple[int, int]]) -> tuple[float, ...]:
    """`LamProbe.admissible`'s all-seeds conjunction, applied to stored counts.

    Kept as a function over the stored fractions rather than as a second
    hand-written tuple: two statements of the same window is the D-047 shape,
    and this one would be the statement that drifts.
    """
    return tuple(sorted(lam for lam, (k, n) in counts.items() if n and k == n))


@dataclass(frozen=True)
class Remeasurement:
    """One `(scene, weight)` cell whose λ window was re-measured off key.

    Counts are stored as `(n_in_band, n)` per `(arm, λ)` rather than as the
    admissible tuple, because `LamProbe.admissible` is a **conjunction over
    seeds** and D-019/Q-042 booked what that costs: a boolean can only tighten
    as `n` grows and cannot be re-scored under any other criterion. The
    fractions can. The 2-seed smoke of the crossing ladder read risk as
    admissible at {0.4, 0.8}; at 16 seeds it is {0.8} alone, and a stored
    boolean would have hidden that 0.4 is 15/16 rather than a clean failure.

    Every window and every grade below is *derived* from `counts`. A
    re-measurement that also stated its own conclusions would be two statements
    of one fact, and the second is the one that goes stale.
    """

    scenario: str
    #: The weight the ladder was walked at — the key the table does not carry.
    weight: float
    seeds: int
    ladder: tuple[float, ...]
    #: Near-miss margin in force, since `admissible` is ESS + completion only
    #: but the walk's safety numbers are read against this.
    margin: float
    measured_on: str
    counts: Mapping[str, Mapping[float, tuple[int, int]]]

    @property
    def arms(self) -> tuple[str, ...]:
        return tuple(self.counts)

    def window(self, arm: str) -> tuple[float, ...]:
        """The re-measured admissible set for one arm at :attr:`weight`."""
        return admissible_at(self.counts[arm])

    def recorded(self, arm: str, path: str = TABLE) -> tuple[float, ...]:
        """The table's window for this cell, read regardless of provenance —
        which is the point: this is the set a caller *would* have used."""
        return lookup(path, self.scenario, arm, self.weight).admissible

    def shift(self, arm: str, path: str = TABLE) -> str:
        """:func:`window_shift` of recorded against re-measured, for one arm."""
        return window_shift(self.recorded(arm, path), self.window(arm))

    def shared(self) -> tuple[float, ...]:
        """Rungs admitting **every** arm — the temperatures at which an A/B on
        this cell has an operating point at all. Empty means the cell cannot be
        walked at one λ, which is a fact about the scene and not about either
        controller."""
        sets = [set(self.window(a)) for a in self.arms]
        return tuple(sorted(set.intersection(*sets))) if sets else ()



"""Directional epistemic-reach screen — which scenes can *hear* `w_epist` at all.

D-021 established that the shadow cost is gated by **rollout reach**, causally
and in both directions (raising the horizon wakes the dead crossing scene,
cutting it kills the known-live one). It also refuted the obvious scalar
summary of that gate in the same pass:

    "live iff max rollout reach >= distance to the nearest unseen cell"

is **false**, and holds on 28 of 92 crossing-scene steps where the measured
per-sample spread is still exactly zero. Rollouts reach far *along* the path;
the shadows sit *lateral to* and *behind* the actors. A distance scalar cannot
express that, so the screen has to carry **direction**.

This module is that screen. It answers, from the scenario yaml and **without
running a controller**, whether a scene's σ > 0 field falls inside the region
MPPI's rollout cloud actually occupies.

**Why it predicts spread rather than intersection.** The natural criterion —
"does the cloud touch any unseen cell" — is the wrong one, and D-021 says why:
`ShadowCostCritic` charges each *sample* `w_epist·Σ_h σ`, and a constant added
to all K sample costs **cancels exactly in the softmax**. A cloud fully inside
the shadow is as inaudible as one fully outside it. So the screen computes the
same per-sample cost vector the critic would, and reports its **spread**
(`ptp`) — the quantity the softmax can actually see. Zero spread is the
signal-free class; any weight is a no-op there.

**Faithful by construction, not by re-derivation.** The fan is generated by the
same `dynamics.step` plant, the same `MPPIParams` noise (`sigma_v`, `sigma_w`),
the same `Limits` clipping and the same warm-start (`v = target_speed`,
`omega = 0`) that `StockMPPI.__init__` sets, and the σ field is rendered by the
same `GTBevProducer` `RiskMPPI` builds. Nothing about the cloud's geometry is
restated here in closed form, so the screen cannot drift from the controller by
someone editing one and not the other.

**The geometry model is exact; its nominal *timing* input is not.** Driven from
the measured closed-loop states and times, `reach_on_trajectory` reproduces
D-021's crossing-scene verdict to the step — `0/92` live, max spread `0.00` —
and the `H = 60` wake with it. Driven from the *nominal* traversal, the same
code reads `5/35` live on that scene. The whole error is in the pose sequence,
and the reason is measurable: the closed loop finishes the crossing scene in
**9.2 s against a 16.7 s nominal**, so the nominal robot is somewhere else at
every time a scheduled actor casts a shadow. Across the eight scenes the
closed-loop / nominal duration ratio spans **0.56x to 15x**, in both
directions.

**The vacuity check needs a floor subtracted, and did not have one.** Ruling
out "the term is dead because nothing was rendered" is what licenses D-021's
"rendered and out of reach" reading, and the quantity used for it —
`grid_unseen` — has a hard non-zero floor that belongs to the *renderer*, not
to any scene: the grid is a square of half-extent `n·res/2 = 4.00 m` while
sensing is a disc of radius `5.00 m`, so the square's corners (out to `5.66 m`)
are unobservable in every render forever. That floor is `112/4096 = 2.73 %`,
and it is what all three obstacle-free scenes report. So `grid_unseen > 0` is
true of every scene ever screened, including a world with nothing in it, and
could never have failed for the reason it was asked. `scene_unseen` /
`renders_ignorance` subtract the floor (`empty_world_unseen`, measured by
rendering an empty world rather than typed). Consequence: on the nominal
driver the deaf class is **not one class** — all three deaf scenes are
*vacuous*, none is "rendered and out of reach"; that case exists so far only on
the measured driver, which is where D-021 found it.

That is a caveat with teeth for anything built on `nominal_traversal`, this
module's `epistemic_reach` included: a scene's hazard field is a **rendezvous
in time**, and a timing model that misses by a factor cannot be trusted to
locate one. `epistemic_reach` is therefore a *prediction to be falsified by
measurement* in `feasibility.py`'s sense; `reach_on_trajectory` is the
measurement it is falsified against, and is what the tests pin. See
`tests/test_epistemic_reach_screen.py`.
"""

from __future__ import annotations

import functools
import os
from dataclasses import dataclass
from typing import Iterable, Sequence

import numpy as np

from .controllers.stock_mppi import MPPIParams
from .dynamics import Limits, step

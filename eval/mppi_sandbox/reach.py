#: Screen sampling step along the nominal traversal. Coarser than
#: `exposure.DT` because each sample pays a full BEV render (the occlusion
#: pass is O(cells x obstacles)); 0.5 s over a ~20 s scene is ~40 renders,
#: which keeps a whole-matrix screen inside a second while still resolving a
#: 0.75 m/s actor to 0.37 m of travel between samples.
DT = 0.5

#: Rollout samples in the fan. The controller draws 256; the screen's output
#: is a *support* property (does the cost vector vary at all), which converges
#: far sooner than a weighted mean would. 64 is checked against 256 in
#: `test_screen_verdict_is_stable_in_fan_size`.
FAN_SAMPLES = 64

#: σ above which a cell counts as "unseen" for the *scalar* comparison below.
#: The spread criterion needs no threshold — it reads the field directly.
UNSEEN_SIGMA = 0.5


@functools.lru_cache(maxsize=8)
def _unseen_floor(n: int, res: float, r_sense: float) -> float:
    """Fraction of cells a producer marks unseen with **nothing in the world**.

    Not a property of any scene. The rendered grid is a square of half-extent
    `n·res/2` centred on the robot, but sensing is a *disc* of radius
    `r_sense`; when the square's corner reaches past the disc (`4.00 m` of
    half-extent against a `5.66 m` corner and a `5.00 m` range, at the shipped
    defaults) those corner cells are unobservable in **every** render, forever,
    for geometric reasons that no obstacle placement can change.

    Measured by rendering an empty world rather than typed, so it tracks
    `grid_size` / `resolution` / `sensing_range` instead of going stale the way
    a hand-copied constant would (D-047's shape). Pose- and time-independent
    because the grid is robot-centred and an empty world casts no shadows —
    both pinned in `test_epistemic_reach_screen.py`.
    """
    probe = GTBevProducer([], grid_size=n, resolution=res, sensing_range=r_sense)
    grid = probe.render(np.zeros(2), 0.0).stack[RiskChannel.EPISTEMIC]
    return float((grid > UNSEEN_SIGMA).mean())


def empty_world_unseen(producer: GTBevProducer) -> float:
    """`_unseen_floor` for a producer's geometry — the floor under `grid_unseen`."""
    return _unseen_floor(producer.n, producer.res, producer.r_sense)


@dataclass(frozen=True)
class ReachProfile:
    """One scene's epistemic audibility along its nominal traversal."""

    scenario: str
    horizon: int
    n_steps: int
    #: Steps where the per-sample shadow-cost spread is > 0 — the softmax can
    #: see the term. This is the screen's verdict.
    live_steps: int
    #: Largest per-sample spread over the traversal, at `w_epist = 1`.
    max_spread: float
    #: Mean fraction of rendered grid cells carrying σ > `UNSEEN_SIGMA`.
    #: **Does not, on its own, separate "no ignorance rendered" (vacuous) from
    #: "rendered and out of reach" (D-021's finding)** — it has a hard floor
    #: that belongs to the renderer's geometry rather than to the scene. Read
    #: `scene_unseen` for the separation this field was believed to make; see
    #: `unseen_floor`.
    grid_unseen: float
    #: `grid_unseen` in an **empty world** under this profile's producer
    #: geometry — the reading a scene with no obstacles at all still gets.
    #: Carried per-profile rather than assumed constant so a non-default
    #: `grid_size` / `sensing_range` cannot silently invalidate the subtraction.
    unseen_floor: float
    #: Steps the *refuted* scalar (`max reach >= nearest unseen`) calls live.
    #: Carried so the screen reports its own improvement over the thing it
    #: replaces, rather than asking a reader to take it on trust.
    scalar_live_steps: int
    #: Steps where the scalar says live and the spread is zero — the **set**
    #: difference, counted per step. `scalar_live_steps - live_steps` equals
    #: this only if the live set nests inside the scalar's, which the two are
    #: not guaranteed to do; see `spread_only_steps`.
    scalar_only_steps: int
    #: The other direction: spread > 0 where the scalar says dead. Measured
    #: rather than assumed away, because it is what makes the subtraction
    #: above legitimate. `0` on all 8 matrix scenes at the shipped horizon —
    #: so the sets *do* nest there, as a measurement rather than a hedge.
    spread_only_steps: int

    @property
    def live_fraction(self) -> float:
        return self.live_steps / self.n_steps if self.n_steps else 0.0

    @property
    def audible(self) -> bool:
        """Can this scene test the epistemic channel at all?"""
        return self.live_steps > 0

    @property
    def scene_unseen(self) -> float:
        """Ignorance this **scene** renders, above the empty-world floor.

        `grid_unseen` was documented as separating "no ignorance rendered"
        (vacuous) from "rendered and out of reach", and it cannot: at the
        shipped geometry an obstacle-free world reads `0.027`, so the vacuous
        class never reads `0` and `grid_unseen > 0` is true of every scene that
        has ever been screened. This is the floor-subtracted quantity that does
        make the separation.
        """
        return max(0.0, self.grid_unseen - self.unseen_floor)

    @property
    def renders_ignorance(self) -> bool:
        """Does the scene itself cast any shadow? The vacuity check.

        This is the predicate `grid_unseen > 0` was standing in for. The two
        disagree on exactly the population the check exists to catch — a scene
        with no obstacles — which is why the disagreement went unseen: every
        scene in the matrix that anyone thought to check was one with
        obstacles in it.
        """
        return self.scene_unseen > 0.0

    @property
    def scalar_false_positives(self) -> int:
        """Steps the scalar calls live where the spread is exactly zero.

        The genuine per-step set difference. It used to be
        `max(0, scalar_live_steps - live_steps)`, a difference of *aggregates*
        that equals the set difference only when the live set nests inside the
        scalar's — which the docstring conceded "need not" happen while the
        `max(0, ...)` quietly floored the case where it didn't. The sets do in
        fact nest on all 8 matrix scenes (`spread_only_steps == 0`), so the old
        number was right; it was right by coincidence, and the coincidence is
        now measured instead of holding the quantity's place (D-046's shape).
        D-021 pinned this at 28/92 for the crossing scene.
        """
        return self.scalar_only_steps

    def __str__(self) -> str:  # pragma: no cover - reporting sugar
        verdict = "AUDIBLE" if self.audible else "deaf   "
        vacuous = "" if self.renders_ignorance else " VACUOUS(no scene shadow)"
        return (f"{verdict} {self.scenario}: H={self.horizon} "
                f"live {self.live_steps}/{self.n_steps} "
                f"({self.live_fraction:.0%}), max spread {self.max_spread:.2f}, "
                f"scene sigma {self.scene_unseen:.1%} "
                f"(grid {self.grid_unseen:.1%} - floor {self.unseen_floor:.1%}), "
                f"scalar would say {self.scalar_live_steps}/{self.n_steps}"
                f"{vacuous}")


def nominal_poses(scenario: Scenario, dt: float = DT) -> np.ndarray:
    """(T, 4) `[t, x, y, yaw]` — the nominal traversal with a tangent heading.

    `exposure.nominal_traversal` gives position only; the fan needs a heading,
    and heading is the whole point of a *directional* screen. Taken as the
    path tangent by forward difference (the reference the tracking cost is
    measured against), with the last sample repeating the previous tangent so
    a stationary final sample does not produce an undefined yaw.
    """
    traj = nominal_traversal(scenario, dt=dt)
    xy = traj[:, 1:3]
    d = np.diff(xy, axis=0)
    yaw = np.arctan2(d[:, 1], d[:, 0])
    if len(yaw) == 0:                       # single-sample degenerate path
        yaw = np.array([float(scenario.start[2])])
    else:
        yaw = np.concatenate([yaw, yaw[-1:]])
    return np.column_stack([traj[:, 0], xy, yaw])


def rollout_fan(pose: np.ndarray, target_speed: float, *,
                params: MPPIParams | None = None, limits: Limits | None = None,
                samples: int = FAN_SAMPLES, seed: int = 0) -> np.ndarray:
    """(K, H, 2) world points of the MPPI rollout cloud from one pose.

    Reproduces `StockMPPI.command`'s first-iteration sampling exactly: the
    warm-start plan `StockMPPI.__init__` installs (`v = target_speed`,
    `omega = 0`), perturbed by `N(0, [sigma_v, sigma_w])`, clipped to `Limits`,
    and rolled through the shared `dynamics.step` plant. The cloud is therefore
    a forward-fanning wedge — which is exactly the structure the refuted scalar
    threw away.
    """
    p = params or MPPIParams()
    lim = limits or Limits()
    rng = np.random.default_rng(seed)
    H = p.horizon
    U = np.zeros((H, 2))
    U[:, 0] = target_speed
    noise = rng.normal(0.0, [p.sigma_v, p.sigma_w], size=(samples, H, 2))
    controls = U[None] + noise
    controls[..., 0] = np.clip(controls[..., 0], lim.v_min, lim.v_max)
    controls[..., 1] = np.clip(controls[..., 1], -lim.omega_max, lim.omega_max)

    # The nominal robot is *at* cruise, not accelerating into it — otherwise
    # the acceleration limit would shorten every fan by the same bias.
    state = np.broadcast_to(
        np.array([pose[1], pose[2], pose[3], target_speed, 0.0]),
        (samples, 5)).copy()
    out = np.empty((samples, H, 2))
    for h in range(H):
        state = step(state, controls[:, h], p.dt, lim)
        out[:, h] = state[:, :2]
    return out


def _grid_distances(producer: GTBevProducer, robot_xy: np.ndarray) -> np.ndarray:
    """(n, n) distance from the robot to each rendered cell center."""
    n, res = producer.n, producer.res
    half = n * res / 2.0
    ax = robot_xy[0] - half + (np.arange(n) + 0.5) * res
    ay = robot_xy[1] - half + (np.arange(n) + 0.5) * res
    cx, cy = np.meshgrid(ax, ay)
    return np.hypot(cx - robot_xy[0], cy - robot_xy[1])


def _profile(name: str, poses: np.ndarray, speeds: np.ndarray, *,
             params: MPPIParams, limits: Limits, producer: GTBevProducer,
             samples: int, seed: int) -> ReachProfile:
    """Core loop, shared by both drivers.

    `poses` is (T, 4) `[t, x, y, yaw]` and `speeds` the (T,) body speed the fan
    is warm-started at. The two drivers differ *only* in what they put in those
    arrays — which is what makes "the geometry is exact, the nominal timing is
    not" a checkable statement rather than a hedge.
    """
    spreads = np.zeros(len(poses))
    unseen_frac = np.zeros(len(poses))
    scalar_live = np.zeros(len(poses), dtype=bool)

    for i, pose in enumerate(poses):
        robot_xy = pose[1:3]
        bev = producer.render(robot_xy, float(pose[0]))
        fan = rollout_fan(pose, float(speeds[i]), params=params, limits=limits,
                          samples=samples, seed=seed)

        # The critic's own arithmetic: per-sample sum of sigma over the
        # horizon, at w_epist = 1. Out-of-grid points take the pessimistic
        # prior sigma = 1.0, matching ShadowCostCritic.
        sigma = bev.sample(RiskChannel.EPISTEMIC, fan.reshape(-1, 2),
                           unobserved_value=1.0)
        spreads[i] = float(np.ptp(sigma.reshape(samples, -1).sum(axis=1)))

        grid = bev.stack[RiskChannel.EPISTEMIC]
        unseen = grid > UNSEEN_SIGMA
        unseen_frac[i] = float(unseen.mean())

        # The refuted scalar, on the same fan and the same field.
        if unseen.any():
            reach = float(np.linalg.norm(fan.reshape(-1, 2) - robot_xy,
                                         axis=1).max())
            scalar_live[i] = reach >= float(
                _grid_distances(producer, robot_xy)[unseen].min())

    live = spreads > 0.0
    return ReachProfile(
        scenario=name,
        horizon=params.horizon,
        n_steps=len(poses),
        live_steps=int(live.sum()),
        max_spread=float(spreads.max()) if len(spreads) else 0.0,
        grid_unseen=float(unseen_frac.mean()) if len(unseen_frac) else 0.0,
        unseen_floor=empty_world_unseen(producer),
        scalar_live_steps=int(scalar_live.sum()),
        scalar_only_steps=int((scalar_live & ~live).sum()),
        spread_only_steps=int((live & ~scalar_live).sum()),
    )


def _with_horizon(params: MPPIParams | None, horizon: int | None) -> MPPIParams:
    p = params or MPPIParams()
    return p if horizon is None else MPPIParams(**{**p.__dict__, "horizon": horizon})


def epistemic_reach(path: str, *, horizon: int | None = None,
                    dt: float = DT, samples: int = FAN_SAMPLES,
                    seed: int = 0, params: MPPIParams | None = None,
                    limits: Limits | None = None,
                    producer: GTBevProducer | None = None) -> ReachProfile:
    """Screen one scenario yaml. Runs no controller and no closed loop.

    Cheap and directional, but driven by `nominal_traversal`, whose timing is
    measurably wrong on every scene in the matrix — see the module docstring
    and `reach_on_trajectory`, which is the same computation on measured input.
    """
    scen = load_scenario(path)
    p = _with_horizon(params, horizon)
    poses = nominal_poses(scen, dt=dt)
    return _profile(os.path.basename(path), poses,
                    np.full(len(poses), scen.target_speed),
                    params=p, limits=limits or Limits(),
                    producer=producer or GTBevProducer(scen.obstacles),
                    samples=samples, seed=seed)


def reach_on_trajectory(scenario: Scenario, traj: np.ndarray, *,
                        horizon: int | None = None, samples: int = FAN_SAMPLES,
                        seed: int = 0, params: MPPIParams | None = None,
                        limits: Limits | None = None,
                        producer: GTBevProducer | None = None) -> ReachProfile:
    """The same screen on a **measured** `(T, 6)` trajectory from `run.simulate`.

    Poses and per-step speed come from the trajectory the controller actually
    executed, and the fan is warm-started at the realized body speed rather
    than at `target_speed_mps` — which the closed loop does not track (0.36 m/s
    of plan against a 0.30 m/s setting on the crossing scene, and 0.54 m/s of
    realized traversal).

    This is not a screen — it costs a simulation, and it is evaluated on the
    trajectory the shadow cost helped produce. Its job is to be the ground
    truth `epistemic_reach` is checked against, and it earns that by
    reproducing D-021's closed-loop verdicts exactly.
    """
    traj = np.asarray(traj, dtype=float)
    # Fan from the state at the *start* of each control step, which is the
    # state `StockMPPI.command` rolls out from; the last row has no step.
    poses = np.column_stack([traj[:-1, 0], traj[:-1, 1], traj[:-1, 2],
                             traj[:-1, 3]])
    return _profile(scenario.name, poses, traj[:-1, 4],
                    params=_with_horizon(params, horizon),
                    limits=limits or Limits(),
                    producer=producer or GTBevProducer(scenario.obstacles),
                    samples=samples, seed=seed)


def screen_scenarios(paths: Iterable[str], **kw) -> list[ReachProfile]:
    """Screen many, audible-first then by descending live fraction — the
    partition into "can test the epistemic channel" and "cannot" is the whole
    output, so return it already ordered."""
    return sorted((epistemic_reach(p, **kw) for p in paths),
                  key=lambda r: (r.audible, r.live_fraction), reverse=True)


def main(argv: Sequence[str] | None = None) -> int:  # pragma: no cover - CLI
    import argparse
    import glob

    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--scenarios", default="eval/scenarios/*.yaml")
    ap.add_argument("--horizon", type=int, default=None,
                    help="override MPPIParams.horizon (D-021's wake/kill knob)")
    ap.add_argument("--dt", type=float, default=DT)
    ap.add_argument("--samples", type=int, default=FAN_SAMPLES)
    args = ap.parse_args(argv)

    from .calibrate_lam import is_scenario_yaml
    paths = [p for p in sorted(glob.glob(args.scenarios)) if is_scenario_yaml(p)]
    profiles = screen_scenarios(paths, horizon=args.horizon, dt=args.dt,
                                samples=args.samples)
    for r in profiles:
        print(r)
    audible = [r for r in profiles if r.audible]
    print(f"\n{len(audible)}/{len(profiles)} scenes can hear the epistemic "
          f"channel at H={profiles[0].horizon if profiles else '?'}")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())

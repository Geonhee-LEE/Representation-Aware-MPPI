"""The per-scene `lam` calibration table, and the Q-035 criterion behind it.

Context (2026-08-02, cycles 12:00 -> 16:00). The shipped `lam = 0.1` puts every
arm this repo has measured below the ESS floor; re-picking one better value
does not repair it, because `cafe_straight_v0`'s admissible window sits ~20x
below the hazard scenes' and the two are **disjoint**. The calibration unit is
therefore the scene. `eval/mppi_sandbox/calibrate_lam.py` measures the windows;
this file pins what the recorded table has to satisfy.

Deliberate cost split (STATE item #6 — the suite went 81 s -> 130 s in one
cycle and D-016 promised "seconds, no ROS needed"): the **wide** ladder is a
script, run on demand. What runs in CI is the table's structure plus one
**narrow** re-measurement, so a stale or hand-edited table is caught without
paying ~500 closed-loop runs per PR.

Nothing here asserts a *particular* temperature is correct. The windows are
measurements; the re-baseline (Q-032) is the branch allowed to act on them.
"""


import pytest

from eval.mppi_sandbox import ab
from eval.mppi_sandbox import calibrate_lam as cal
from eval.mppi_sandbox.scenario import load_scenario

TABLE = "eval/scenarios/lam_windows.yaml"
REPO_SCENARIOS = "eval/scenarios"


@pytest.fixture(scope="module")
def table() -> dict:
    if not os.path.exists(TABLE):
        pytest.skip(f"{TABLE} not generated — run "
                    f"`python3 -m eval.mppi_sandbox.calibrate_lam`")
    return cal.load_windows(TABLE)


def test_table_covers_every_scenario_in_the_repo(table):
    """A calibration table that silently omits a scene is worse than none —
    the omitted scene keeps getting compared at the shipped `lam = 0.1` while
    the table's existence implies the question was asked."""
    on_disk = {f for f in os.listdir(REPO_SCENARIOS) if f.endswith(".yaml")}
    on_disk.discard(os.path.basename(TABLE))
    covered = {scenario for scenario, _ in table}
    # D-477: **the two debts came apart, and this is the line that said it
    # would.** It used to borrow `scene_census.UNHARVESTED_SCENES` as the
    # tolerated set, with the standing note that a lam window is a ladder sweep
    # and not a seed-0 ensemble, so the reuse held only while one scene
    # (`cafe_obstacle_contested_v0`) happened to owe both.
    #
    # D-470's regeneration bought the lam column for that scene — 9 scenes x 8
    # controllers, all walked — so the lam debt is now **zero**. The arm-column
    # debt is untouched: `UNHARVESTED_SCENES` still names the same scene,
    # because no seed-0 ensemble was run for it and a ladder sweep is not one.
    # Borrowing the pin for one more cycle would have made this test green by
    # tolerating a scene the table actually covers, which is the direction
    # `UNHARVESTED_SCENES`'s own docstring forbids ("never widen it to make a
    # suite green" — reusing it as slack here is the same move from outside).
    assert on_disk - covered == set(), (
        f"uncalibrated scenes: {sorted(on_disk - covered)} — the table is "
        f"expected to span every shipped scene as of D-477")


def test_every_cell_names_a_registered_controller(table):
    from eval.mppi_sandbox.controllers import REGISTRY

    for _, controller in table:
        assert controller in REGISTRY, controller


def test_recorded_windows_are_rungs_of_the_recorded_ladder(table):
    """Guards against a hand-edited table: an "admissible" temperature that
    was never a rung was never measured.

    Checked against each cell's **own** ladder, not `DEFAULT_LADDER` — refined
    cells carry bisected rungs the default ladder never had, and pinning the
    global constant here would either reject those or force the refinement to
    round onto a coarse grid it exists to escape.
    """
    for key, cell in table.items():
        assert set(cell["admissible"]) <= set(cell["ladder"]), (
            key, cell["admissible"], cell["ladder"])


def test_every_cell_measured_at_least_the_default_ladder(table):
    """Refinement may only *add* rungs. A cell missing a default rung was
    generated by a narrowed run and its empty window means less than it
    appears."""
    default = set(cal.DEFAULT_LADDER)
    for key, cell in table.items():
        assert default <= set(cell["ladder"]), (
            key, sorted(default - set(cell["ladder"])))


def test_calibratable_flag_agrees_with_the_window(table):
    for key, cell in table.items():
        assert cell["calibratable"] == bool(cell["admissible"]), key


#: Cells whose empty window is explained by a **third** cause the two-way split
#: below does not model: a per-seed ESS spread of *exactly* `1.00x`. D-477's
#: install surfaced the first one — 8 controllers x 9 scenes turned up a cell
#: the 3-controller table could not have contained.
#:
#: `min_spread == 1.0` means max/min ESS over the ladder is one, i.e. the
#: ensemble does not spread **at all** across seeds. That is not a scatter too
#: wide for the band (Q-035) and not an arm that fails to finish (Q-034,
#: `completes_anywhere` is true here) — it is an arm whose ESS is constant, so
#: no rung distinguishes itself and the window comes out empty for a reason
#: neither existing class names. Whether the right reading is "degenerate
#: weighting" or "the ladder never moved the softmax" was Q-206 — **answered
#: 2026-08-28, and it is neither** (D-482).
#:
#: `min_spread == 1.0` here is an artifact of the *statistic*, not a property
#: of the ensemble: the two lowest rungs pin every seed at the ESS floor and
#: `min_spread` minimises over the whole ladder including them. Over the rungs
#: that reach the band the spread is 6.4x-110x, and the ESS response to `lam`
#: is non-monotone, so bisection cannot close it either. See
#: `min_reachable_spread` and `MEASURED_CROSSING_CBF` at the foot of this file.
#:
#: Pinned, not tolerated as a predicate. Widening the two tests below to accept
#: any `min_spread == 1.0` cell would silently absorb every future one; naming
#: this cell means a second occurrence is still a red.
DEGENERATE_SPREAD: frozenset[tuple[str, str]] = frozenset({
    ("cafe_obstacle_crossing_v0.yaml", "cbf_mppi"),
})


def test_the_degenerate_spread_pin_still_describes_the_table(table):
    """Non-vacuity for the pin above. A pin that stops matching any cell reads
    exactly like a clean table (D-317), so the cells it names must still be
    present, still empty-windowed, and still spread at exactly 1.00x — if the
    cell were recalibrated into a window, this pin is what should be deleted.
    """
    for key in DEGENERATE_SPREAD:
        assert key in table, f"{key} left the table — delete it from the pin"
        cell = table[key]
        assert not cell["calibratable"], f"{key} now has a window; unpin it"
        assert cell["completes_anywhere"], key
        assert cell["min_spread"] == 1.0, (
            f"{key} spread moved to {cell['min_spread']} — it is no longer the "
            f"degenerate case this pin exempts, so it must be re-classified")


def test_empty_windows_are_structural_not_ladder_artifacts(table):
    """Q-035's substance. An empty window is only a *reportable* finding if no
    rung **could** have qualified — otherwise it is a coarse ladder.

    The structural test is the width argument from 14:00: a rung qualifies only
    if every seed lands inside the band, so if the narrowest per-seed spread
    over the whole ladder already exceeds the band's width, no temperature can
    contain the ensemble and adding rungs is wasted compute. Cells that fail
    this are not errors — they are exactly the cells where "run a finer ladder"
    is the right next action, and this test makes that visible instead of
    letting an empty window read as a settled negative.
    """
    unexplained = [
        key for key, cell in table.items()
        if not cell["calibratable"]
        and cell["completes_anywhere"]
        and cell["min_spread"] <= cal.band_width()
        and key not in DEGENERATE_SPREAD
    ]
    assert not unexplained, (
        f"empty window but spread fits inside the band for {unexplained} — "
        f"a finer ladder near the crossing may find a rung; do not report "
        f"these as 'no admissible temperature exists'")


def test_empty_windows_name_which_failure_they_are(table):
    """Every empty window must be attributable to one of exactly two causes,
    because the right next action differs completely between them.

    * `completes_anywhere = false` — the arm never finishes at any tested
      temperature. Not a temperature problem; no ladder fixes it, and the
      scene (or the arm's speed/horizon) is what needs attention. This is the
      Q-034 shape, found here on `cafe_cut_in_v0` at a per-seed ESS spread of
      1.00x — perfectly reproducible and still uncalibratable.
    * `min_spread > band_width` — the seeds scatter wider than the band, so no
      single rung can hold the ensemble. The Q-035 shape (`offset = 0.3`).

    A cell that is neither is a ladder-density artifact, caught by the test
    above. Conflating the two is how 15:00 nearly reported "wrong decade" as
    "no value works".
    """
    for key, cell in table.items():
        if cell["calibratable"] or key in DEGENERATE_SPREAD:
            continue
        assert (not cell["completes_anywhere"]
                or cell["min_spread"] > cal.band_width()), key


def test_no_shared_temperature_serves_the_whole_matrix(table):
    """Q-025's constructive form, pinned as a regression.

    Not an aspiration — a measurement. If a future change (a wider band, a
    different scene set, a cost rescale) makes this pass again, a fixed-`lam`
    ablation becomes admissible and several open questions collapse, so this
    failing is *good news that must not pass silently*.
    """
    shared = set.intersection(
        *(set(cell["admissible"]) for cell in table.values())) if table else set()
    assert not shared, (
        f"a shared temperature now exists ({sorted(shared)}) — the per-scene "
        f"calibration protocol may be replaceable by a fixed `lam`; re-open "
        f"Q-025 rather than deleting this test")


def test_no_shared_temperature_even_among_the_calibratable_cells(table):
    """The claim that matters, stated so it cannot be dismissed.

    `test_no_shared_temperature_serves_the_whole_matrix` includes
    `cafe_cut_in_v0`, whose window is empty because the arm never finishes —
    an empty intersection would follow trivially from that one dead cell and
    would say nothing about temperature. Excluding it, the intersection is
    *still* empty: the cafe scenes are admissible at {0.2, 0.4} while
    `city_curved_v0` is admissible only at {1.6, 6.4}. Disjoint, between two
    shipped scenario files, with every arm completing.
    """
    live = [cell["admissible"] for cell in table.values() if cell["calibratable"]]
    assert live, "no calibratable cells at all — the table is not usable"
    shared = set.intersection(*(set(w) for w in live))
    assert not shared, (
        f"calibratable cells now share {sorted(shared)} — a fixed-`lam` "
        f"ablation may be admissible again; re-open Q-025")


def test_windows_are_not_all_the_same_scene_to_scene(table):
    """The disjointness that forces per-scene calibration. If every scene had
    the same window the table would be a constant and this whole module would
    be over-engineering."""
    windows = {frozenset(cell["admissible"])
               for cell in table.values() if cell["admissible"]}
    assert len(windows) > 1, (
        "every calibratable scene shares one window — collapse the table")


@pytest.mark.parametrize("scenario_file", ["cafe_straight_v0.yaml"])
def test_recorded_window_reproduces_on_a_narrow_ladder(table, scenario_file):
    """The one live re-measurement, kept narrow on purpose (3 rungs x 4 seeds,
    a few seconds) — enough to catch a table generated against different code,
    cheap enough to run on every PR.

    `cafe_straight_v0` is the fixture because it is the best-conditioned scene
    in the repo (per-seed spread ~1.2x, three consecutive admissible rungs at
    n = 8), so a narrow ladder over it is reproducible rather than a knife
    edge. Reproducing on a *pathological* scene would be the flaky choice.
    """
    key = (scenario_file, "stock_mppi")
    if key not in table:
        pytest.skip(f"{key} not in table")
    recorded = table[key]["admissible"]
    if not recorded:
        pytest.skip("no recorded window to reproduce")

    scenario = load_scenario(os.path.join(REPO_SCENARIOS, scenario_file))
    probes = ab.lam_ladder(scenario, "stock_mppi", recorded[:1], seeds=range(4))
    assert probes[0].admissible, (
        f"recorded window {list(recorded)} does not reproduce at "
        f"lam={probes[0].lam}: median_ess={probes[0].median_ess:.1f}, "
        f"{probes[0].n_in_band}/{probes[0].n} in band, "
        f"reached={probes[0].all_reached} — the table is stale relative to "
        f"the controller code")


def test_shared_window_helper_intersects_cells():
    """Pure-function check on `shared_window`, no simulation."""
    a = cal.SceneCalibration("a.yaml", "stock_mppi", (0.2, 0.4, 0.8))
    b = cal.SceneCalibration("b.yaml", "stock_mppi", (0.8, 1.6))
    c = cal.SceneCalibration("c.yaml", "stock_mppi", (3.2,))
    assert cal.shared_window([a, b]) == (0.8,)
    assert cal.shared_window([a, b, c]) == ()
    assert cal.shared_window([]) == ()


def test_band_width_derives_from_the_band_constants():
    """`band_width` must track `ab.ESS_BAND_FRACTIONS`, because Q-035 option
    (a) is "widen the band" — if that is ever taken, the structural threshold
    in `test_empty_windows_are_structural...` has to move with it, not stay
    pinned at 10x."""
    lo, hi = ab.ESS_BAND_FRACTIONS
    assert cal.band_width() == pytest.approx(hi / lo)


def _probe(lam, *, in_band, n=8, reached=True, lo=10.0, hi=12.0):
    return ab.LamProbe(lam=lam, median_ess=(lo + hi) / 2, min_ess=lo,
                       max_ess=hi, n_in_band=n if in_band else 0, n=n,
                       all_reached=reached)


def test_refinement_is_skipped_when_the_arm_never_completes():
    """The distinction that cost this cycle a re-run. `cafe_cut_in_v0` has a
    per-seed ESS spread of 1.00x — as reproducible as a scene gets — and still
    no admissible rung, because no temperature gets every seed to the goal.
    Bisecting it burns simulation on a question the ladder cannot answer.
    """
    never = cal.SceneCalibration(
        "cut_in.yaml", "stock_mppi", (),
        probes=(_probe(0.2, in_band=True, reached=False),
                _probe(0.4, in_band=True, reached=False)))
    assert not never.completes_anywhere
    assert not cal.needs_refinement(never)

    crossable = cal.SceneCalibration(
        "gap.yaml", "stock_mppi", (),
        probes=(_probe(0.2, in_band=False), _probe(0.4, in_band=False)))
    assert crossable.completes_anywhere
    assert cal.needs_refinement(crossable), (
        "narrow spread + completes + empty window => the ladder stepped over "
        "the crossing; this is the one case bisection is for")


def test_wide_spread_empty_window_is_not_refined():
    """Q-035's structural case: spread wider than the band, so no rung can
    hold the ensemble and a finer ladder is wasted compute."""
    wide = cal.SceneCalibration(
        "offset03.yaml", "risk_mppi", (),
        # 18x — the worst per-seed spread measured on `offset = 0.3` (lam 1.4,
        # 2026-08-02 14:00), against a band that only spans 10x.
        probes=(_probe(1.4, in_band=False, lo=3.0, hi=54.0),))
    assert wide.min_spread > cal.band_width()
    assert not cal.needs_refinement(wide)


def test_refine_ladder_bisects_in_log_space_around_the_best_rung():
    part = cal.SceneCalibration(
        "s.yaml", "stock_mppi", (),
        probes=(_probe(0.2, in_band=False, n=8),
                ab.LamProbe(lam=0.4, median_ess=11.0, min_ess=10.0,
                            max_ess=12.0, n_in_band=6, n=8, all_reached=True),
                _probe(0.8, in_band=False, n=8)))
    extra = cal.refine_ladder(part)
    assert extra == (round((0.4 * 0.2) ** 0.5, 4), round((0.4 * 0.8) ** 0.5, 4))
    assert all(0.2 < x < 0.8 for x in extra)


